MACE_FOUNDATION_WORKFLOW_OWNED_NATIVE_FIELDS = {
    "name",
    "work_dir",
    "train_file",
    "test_file",
    "model",
    "foundation_model",
    "mace_backend",
}

MaceFoundationRunner = Callable[[dict[str, Any]], None]


def load_mace_foundation_train_config(config_path: str | Path) -> dict[str, Any]:
    resolved = Path(config_path).resolve()
    payload = read_json(resolved)
    if not isinstance(payload, dict):
        raise ValueError(f"MACE teacher foundation train config must be an object: {resolved}")

    workflow = payload.get("workflow")
    if not isinstance(workflow, dict):
        raise ValueError(f"MACE teacher foundation train config requires a 'workflow' block: {resolved}")
    native = payload.get("mace")
    if not isinstance(native, dict):
        raise ValueError(f"MACE teacher foundation train config requires a 'mace' block: {resolved}")

    misplaced = sorted(set(native) & MACE_FOUNDATION_WORKFLOW_OWNED_NATIVE_FIELDS)
    if misplaced:
        raise ValueError(
            f"Invalid MACE teacher foundation config {resolved}: workflow-owned field(s) {misplaced} must be "
            "under 'workflow' or generated by the workflow, not the native 'mace' block"
        )

    model_family = str(workflow.get("model_family", "")).strip().lower()
    if not model_family:
        raise ValueError(f"MACE teacher foundation workflow.model_family is required: {resolved}")
    mace_backend = normalize_mace_backend(model_family)

    training_data = workflow.get("training_data")
    if not isinstance(training_data, dict):
        raise ValueError(f"MACE teacher foundation workflow.training_data must be an object: {resolved}")
    base_datasets = training_data.get("base_datasets")
    if not isinstance(base_datasets, list) or not base_datasets:
        raise ValueError(
            f"MACE teacher foundation workflow.training_data.base_datasets must be a non-empty list: {resolved}"
        )

    normalized_workflow = dict(workflow)
    normalized_workflow["model_family"] = mace_backend
    normalized_workflow["training_data"] = dict(training_data)
    return {
        "backend_name": "mace",
        "workflow": normalized_workflow,
        "backend_native": dict(native),
        "native_config": dict(native),
        "source_path": str(resolved),
        "model_family": mace_backend,
        "mace_backend": mace_backend,
        "training_data": dict(training_data),
    }


def _write_json(path: str | Path, payload: Any) -> Path:
    resolved = Path(path).resolve()
    resolved.parent.mkdir(parents=True, exist_ok=True)
    resolved.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    return resolved


def _workspace_root(request: TeacherFoundationTrainRequest, config_path: Path) -> Path:
    if request.context.get("workspace_root"):
        return Path(str(request.context["workspace_root"])).resolve()
    if request.paths is not None and getattr(request.paths, "workspace_root", None) is not None:
        return Path(request.paths.workspace_root).resolve()
    return config_path.parent.resolve()


def _resolve_training_datasets(train_cfg: dict[str, Any], *, workspace_root: Path) -> list[Path]:
    training_data = dict(train_cfg.get("training_data", {}) or {})
    return validate_path_only_xyz_list(
        training_data.get("base_datasets"),
        field_name="teacher_foundation_train.training_data.base_datasets",
        bare_filename_root=workspace_root / "user_assets" / "teacher_foundation_train",
    )


def _default_mace_foundation_runner(run_cfg: dict[str, Any]) -> None:
    env = dict(run_cfg.get("execution_env") or os.environ.copy())
    env.setdefault("MKL_THREADING_LAYER", "GNU")
    train_request = {
        "rendered_yaml": run_cfg["rendered_yaml"],
        "execution": run_cfg["execution"],
    }
    if run_cfg.get("mace_run_train_executable"):
        train_request["mace_run_train_executable"] = run_cfg["mace_run_train_executable"]
    run_mace_training(train_request, env=env, log_file=run_cfg["train_log"], quiet=True)


def run_mace_foundation_train(
    request: TeacherFoundationTrainRequest,
    *,
    runner: MaceFoundationRunner | None = None,
) -> dict[str, Any]:
    config_path = Path(str(request.cfg.get("config", ""))).resolve()
    if not str(config_path):
        raise ValueError("MACE teacher foundation train requires cfg.config")
    train_cfg = load_mace_foundation_train_config(config_path)
    workspace_root = _workspace_root(request, config_path)
    artifact_root = Path(request.artifact_root).resolve()
    input_root = artifact_root / "input"
    foundation_root = Path(request.foundation_model_root).resolve()
    backend_log_dir = Path(request.backend_log_dir).resolve()
    foundation_root.mkdir(parents=True, exist_ok=True)
    backend_log_dir.mkdir(parents=True, exist_ok=True)

    source_files = _resolve_training_datasets(train_cfg, workspace_root=workspace_root)
    merged_xyz = input_root / "train_merged.xyz"
    merge_xyz_files(source_files, merged_xyz)

    backend = normalize_mace_backend(train_cfg["model_family"])
    active_runner = runner or _default_mace_foundation_runner
    execution = normalize_backend_request_context(request, role=teacher_backend_role("mace", "foundation_train")).execution
    if runner is None:
        env_report = ensure_backend_environment(backend, probe_mace_environment(execution.context))
        print_backend_banner(env_report, backend)
    else:
        env_report = {
            "repo_mode_guess": "fake-runner",
            "has_mace_les_class": backend == "les",
        }

    raw_model_path = artifact_root / "mace_foundation.model"
    foundation_model = foundation_root / "mace_foundation.model"
    mace_train_cfg = copy.deepcopy(train_cfg["native_config"])
    mace_train_cfg.update(
        {
            "name": "mace_foundation",
            "train_file": str(merged_xyz.resolve()),
            "test_file": str(merged_xyz.resolve()),
            "work_dir": str(artifact_root),
        }
    )
    mace_train_cfg = apply_backend_to_train_config(mace_train_cfg, backend)
    mace_train_cfg["execution"] = execution
    rendered_yaml = write_mace_rendered_yaml(mace_train_cfg, artifact_root / "rendered_mace.yaml")
    audit_train_cfg = copy.deepcopy(mace_train_cfg)
    audit_train_cfg.pop("execution", None)
    execution_env = execution.merge_env(os.environ, {"MKL_THREADING_LAYER": "GNU"})
    run_cfg = {
        "backend": "mace",
        "model_family": backend,
        "artifact_root": str(artifact_root),
        "source_config": str(config_path),
        "source_datasets": [str(path.resolve()) for path in source_files],
        "merged_xyz": str(merged_xyz.resolve()),
        "raw_model_path": str(raw_model_path.resolve()),
        "foundation_model": str(foundation_model.resolve()),
        "train_log": str((backend_log_dir / "foundation_train.log").resolve()),
        "rendered_yaml": str(rendered_yaml.resolve()),
        "train_config": copy.deepcopy(mace_train_cfg),
        "execution": execution,
        "execution_context": None if execution.context is None else execution.context.to_payload(),
        "execution_env": execution_env,
        "execution_diagnostics": execution.redacted_diagnostics(),
        **copy.deepcopy(audit_train_cfg),
    }

    active_runner(run_cfg)

    if not raw_model_path.exists() or raw_model_path.stat().st_size <= 0:
        raise RuntimeError(f"MACE foundation training did not produce a model: {raw_model_path}")
    shutil.copyfile(raw_model_path, foundation_model)
    if not foundation_model.exists() or foundation_model.stat().st_size <= 0:
        raise RuntimeError(f"MACE foundation model not published: {foundation_model}")

    metadata_path = write_mace_model_metadata(
        artifact_root,
        backend=backend,
        model_role="foundation",
        env_report=env_report,
        extra={"foundation_model": str(foundation_model.resolve()), "runtime_config": str(request.runtime_json.resolve())},
    )
    runtime_payload = {
        "backend": "mace",
        "model_family": backend,
        "source_config": str(config_path),
        "source_datasets": [str(path.resolve()) for path in source_files],
        "merged_xyz": str(merged_xyz.resolve()),
        "train_config": copy.deepcopy(audit_train_cfg),
        "rendered_yaml": str(rendered_yaml.resolve()),
        "execution_context": execution.redacted_diagnostics(),
        "backend_metadata": str(metadata_path.resolve()),
        "raw_model": str(raw_model_path.resolve()),
        "foundation_model": str(foundation_model.resolve()),
        "train_log": str((backend_log_dir / "foundation_train.log").resolve()),
    }
    _write_json(request.runtime_json, runtime_payload)
    return {
        "backend": "mace",
        "model_family": backend,
        "foundation_model": str(foundation_model.resolve()),
    }
