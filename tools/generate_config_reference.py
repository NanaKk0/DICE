"""Extract the shipped loader's closed key sets without importing runtime engines.

This is a bounded AST inventory, not an independent validator or JSON Schema.
Conditional branches are deliberately unioned and labelled; semantic requirements
remain in configuration.md and in the official loader/preflight.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("workflow_core/lifecycle/config.py")
DESTINATION = Path("docs/configuration-fields.md")


def strings(node: ast.AST, names: dict[str, set[str]]) -> set[str]:
    if isinstance(node, (ast.Set, ast.List, ast.Tuple)):
        return {item.value for item in node.elts if isinstance(item, ast.Constant) and isinstance(item.value, str)}
    if isinstance(node, ast.Name):
        return names.get(node.id, set())
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        return strings(node.left, names) | strings(node.right, names)
    if isinstance(node, ast.IfExp):
        return strings(node.body, names) | strings(node.orelse, names)
    if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id in {"set", "frozenset"} and node.args:
        return strings(node.args[0], names)
    return set()


def inventory(source: str) -> str:
    tree = ast.parse(source)
    globals_: dict[str, set[str]] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    globals_[target.id] = strings(node.value, globals_)
    required = globals_["_REQUIRED_TOP_LEVEL_FIELDS"]
    rows: list[tuple[int, str, str, set[str]]] = []
    for function in tree.body:
        if not isinstance(function, ast.FunctionDef):
            continue
        names = {key: set(value) for key, value in globals_.items()}
        # Union all assignments/conditional additions: per-kind restrictions are
        # intentionally not reconstructed by this small documentation generator.
        for node in ast.walk(function):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name):
                        names.setdefault(target.id, set()).update(strings(node.value, names))
            elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name) and isinstance(node.op, ast.BitOr):
                names.setdefault(node.target.id, set()).update(strings(node.value, names))
            elif (isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute)
                  and isinstance(node.func.value, ast.Name) and node.func.attr == "add"
                  and len(node.args) == 1 and isinstance(node.args[0], ast.Constant)
                  and isinstance(node.args[0].value, str)):
                names.setdefault(node.func.value.id, set()).add(node.args[0].value)
        for node in ast.walk(function):
            if not (isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "_mapping_fields"):
                continue
            keys = strings(node.args[1], names)
            if not keys:
                raise ValueError(f"unresolved mapping allowlist in {function.name}:{node.lineno}")
            label = ast.unparse(node.args[2]).replace("|", "&#124;")
            rows.append((node.lineno, function.name, label, keys))
    lines = [
        "# Generated loader key inventory", "",
        "Generated by `python tools/generate_config_reference.py` from",
        f"`{SOURCE}` using static analysis. Check drift with `--check`.", "",
        "This inventory lists accepted keys. Branch-dependent keys are unioned (notably condition",
        "kinds and teacher/student p-band helpers). Requiredness, defaults, units and",
        "cross-field rules are in [configuration.md](configuration.md) and enforced",
        "by the real loader. Expressions below are the loader's field labels;",
        "`prefix` means the currently visited condition group or segment.", "",
        "Required top-level keys: " + ", ".join(f"`{key}`" for key in sorted(required)) + ".", "",
        "Optional top-level keys: " + ", ".join(f"`{key}`" for key in sorted(globals_["_TOP_LEVEL_FIELDS"] - required)) + ".", "",
        "| Loader owner / line | Object label | Accepted keys (conditional union) |",
        "| --- | --- | --- |",
    ]
    for line, function, label, keys in sorted(rows):
        lines.append(f"| `{function}:{line}` | `{label}` | " + ", ".join(f"`{key}`" for key in sorted(keys)) + " |")
    lines += ["", "Temperature-program segments and symmetric-strain endpoint components are",
              "validated with exact-set comparisons: see",
              "the explicit segment/cell reference in [configuration.md](configuration.md).", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = inventory((ROOT / SOURCE).read_text(encoding="utf-8"))
    destination = ROOT / DESTINATION
    if args.check:
        if not destination.is_file() or destination.read_text(encoding="utf-8") != generated:
            parser.exit(1, "Configuration-key inventory drift; regenerate and review semantics.\n")
        print("Configuration-key inventory matches the shipped loader.")
    else:
        destination.write_text(generated, encoding="utf-8")
        print(f"Wrote {DESTINATION}")


if __name__ == "__main__":
    main()
